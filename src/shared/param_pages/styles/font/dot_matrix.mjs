/**
 * styles/font/dot_matrix.mjs — SET 12, option 8: dot-matrix — the square skeleton on a visible 2px lattice.
 *
 * Every glyph is a four- or five-column form with a blank column inserted
 * between each pair, so the face occupies 7 or 9 columns and every lit pixel
 * lands on an even one. Horizontal bars come out dotted and stems stay
 * continuous, which is what an LED sign looks like.
 *
 * The skeleton is option 2's, and that was measured rather than picked. The
 * rounded skeleton was tried first and came apart: a chamfer is a single
 * pixel, and a single pixel on a 2px lattice is an isolated dot with nothing
 * to group it to, so every bowl dissolved into noise. Square has no isolated
 * pixels anywhere — every stroke is a run of three or more — and a run
 * survives being dotted.
 *
 * The advance is w + 3 where every other option uses w + 1. At w + 1 the gap
 * BETWEEN glyphs is one blank column, which is exactly the gap inside them,
 * so letterspacing and lattice had the same rhythm and the eye could not
 * find a word boundary.
 *
 * Sharing a skeleton with option 2 is then the point rather than an
 * economy: the pair is the cleanest demonstration in the catalog that the
 * RENDERING rule and the letterform are separable choices.
 *
 * Glyph format is font4x5.mjs's exactly — [advance, yOff, w, h, ...rowBits]
 * with bit0 = leftmost pixel — in CHARS order, so a caller can swap one table
 * for the other. Nothing here ships; production draw code imports nothing
 * from this directory.
 */

