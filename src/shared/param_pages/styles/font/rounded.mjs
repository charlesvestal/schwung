/**
 * styles/font/rounded.mjs — SET 12, option 4: rounded — 4-wide with the corner pixels dropped.
 *
 * The rule is applied to every closed or partly closed shape: O C G D Q S P
 * R B lose the pixel at each corner of their bowl, so a bowl is a chamfered
 * octagon rather than a rectangle. A becomes a point and T gets a tucked
 * foot. The result is the only face here with no square corner on a curve.
 *
 * U takes a fifth column, which is a cost the rule forced rather than a
 * choice: a 4-wide U whose bowl is chamfered two rows deep reads as a V, and
 * the specimen came out as AMPLITVDE. Five columns leaves the curve
 * somewhere to go.
 *
 * Glyph format is font4x5.mjs's exactly — [advance, yOff, w, h, ...rowBits]
 * with bit0 = leftmost pixel — in CHARS order, so a caller can swap one table
 * for the other. Nothing here ships; production draw code imports nothing
 * from this directory.
 */

