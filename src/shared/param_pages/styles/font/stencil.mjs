/**
 * styles/font/stencil.mjs — SET 12, option 6: stencil — 4-wide with a 1px break in every enclosed counter.
 *
 * Wherever a stroke would close a counter, one pixel of that stroke is
 * removed: A B D O P Q R break in the bowl, U breaks in the stem, E F L lose
 * their outermost column so no bar ever reaches a corner. I is left whole —
 * it has no counter to open, and a broken 1px stem is not a stencil I, it is
 * an exclamation mark: drawn that way first, SINE read as S!NE. The counter
 * is therefore always connected to the outside of the glyph, which is what
 * a physical stencil requires and what no other face here does.
 *
 * Glyph format is font4x5.mjs's exactly — [advance, yOff, w, h, ...rowBits]
 * with bit0 = leftmost pixel — in CHARS order, so a caller can swap one table
 * for the other. Nothing here ships; production draw code imports nothing
 * from this directory.
 */

