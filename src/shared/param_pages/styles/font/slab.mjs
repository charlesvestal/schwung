/**
 * styles/font/slab.mjs — SET 12, option 5: slab — 4-wide with 1px serifs on the stem terminals.
 *
 * At four pixels there is no room to hang a serif off the side of a stem, so
 * the serif is expressed the only way the grid allows: as a full-width bar
 * at the terminal. A picks up a slab apex, F and P a two-pixel foot, L and I
 * head and foot bars, U closes flat — so every STEM in the face begins and
 * ends on a horizontal.
 *
 * T is the exception, and it is forced: a T with a foot bar IS an I. Drawn
 * that way first, the face put two glyphs in AMPLITUDE that differed by one
 * pixel in the bottom-right corner. The T here keeps a bare stem, and the
 * face gives up a serif rather than a letter.
 *
 * Glyph format is font4x5.mjs's exactly — [advance, yOff, w, h, ...rowBits]
 * with bit0 = leftmost pixel — in CHARS order, so a caller can swap one table
 * for the other. Nothing here ships; production draw code imports nothing
 * from this directory.
 */

